begin;

create table public.recipes (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name_ko text not null check (length(trim(name_ko)) > 0),
  name_en text not null check (length(trim(name_en)) > 0),
  romanized text not null,
  description_ko text not null,
  description_en text not null,
  image text not null check (image ~ '^/images/[A-Za-z0-9_-]+\.(jpg|jpeg|png|webp)$'),
  category text not null,
  cooking_time integer not null check (cooking_time > 0),
  difficulty text not null check (difficulty in ('Easy', 'Medium', 'Hard')),
  spicy_level integer not null check (spicy_level between 0 and 5),
  tags text[] not null default '{}',
  is_published boolean not null default false,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index recipes_published_order_idx on public.recipes (display_order, id) where is_published;

create function public.kfood_set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
create trigger recipes_updated_at before update on public.recipes
for each row execute function public.kfood_set_updated_at();

alter table public.recipes enable row level security;
revoke all on public.recipes from anon, authenticated;
grant select on public.recipes to anon, authenticated;
create policy "Read published recipes" on public.recipes
for select to anon, authenticated using (is_published = true);



